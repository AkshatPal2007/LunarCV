import {test,expect} from '@playwright/test';
import {mkdir} from 'node:fs/promises';
test('real backend connection, accessible controls and responsive empty state',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.setViewportSize({width:1440,height:1100});await page.goto('/');
 await expect(page.getByText('Backend connected')).toBeVisible();
 await expect(page.getByRole('heading',{name:'Registration lab.'})).toBeVisible();
 await expect(page.getByRole('button',{name:'Run registration'})).toBeDisabled();
 await expect(page.getByRole('alert')).toHaveCount(0);
 await mkdir('../outputs/verification',{recursive:true});
 await page.screenshot({path:'../outputs/verification/workspace-desktop-empty.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await expect(page.getByRole('heading',{name:'Registration lab.'})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 await page.screenshot({path:'../outputs/verification/workspace-mobile-empty.png',fullPage:true});
 expect(errors).toEqual([]);
});
test('real mission pair produces traceable rejected products',async({page})=>{
 test.skip(process.env.LUNARCV_REAL_DATA!=='1','Requires locally acquired OHRC/LRO files and model weights; never replaces them with fixtures.');
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.setViewportSize({width:1440,height:1100});await page.goto('/');
 await expect(page.getByText('Backend connected')).toBeVisible();
 const scene=page.getByLabel('Available real scene');
 await scene.selectOption({index:1});
 await page.getByRole('button',{name:'Run registration'}).click();
 await expect(page.getByText('Quality gate rejected this registration')).toBeVisible({timeout:150000});
 await expect(page.getByText('Not measured',{exact:true})).toBeVisible();
 await expect(page.getByLabel('Selected correspondence')).toBeVisible();
 await expect(page.getByRole('button',{name:'Select correspondence 1 on source',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Select correspondence 2 on source',exact:true}).focus();await page.keyboard.press('Enter');
 await expect(page.getByLabel('Selected correspondence')).toHaveValue('2');
 await expect(page.getByRole('alert')).toHaveCount(0);
 await page.screenshot({path:'../outputs/verification/workspace-desktop-result.png',fullPage:true});
 await page.getByRole('button',{name:'Overlay',exact:true}).click();
 await expect(page.getByAltText('Registered source quicklook')).toBeVisible();
 await page.getByLabel('Source opacity').fill('30');
 await page.getByLabel('Show correspondence support hull').check();
 await page.screenshot({path:'../outputs/verification/workspace-overlay.png',fullPage:true});
 await page.getByRole('button',{name:'Checkerboard',exact:true}).click();
 await expect(page.getByAltText('Checkerboard',{exact:true})).toBeVisible();
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 await page.screenshot({path:'../outputs/verification/workspace-mobile-result.png',fullPage:true});
 await page.reload();await page.getByRole('button').filter({hasText:'REJECT'}).first().click();
 await expect(page.getByText('Quality gate rejected this registration')).toBeVisible();
 expect(errors).toEqual([]);
});
